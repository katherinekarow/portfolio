"""Command line.

  python -m formulakit list                         # every formula, by group
  python -m formulakit npv --rate 0.08 --flows "-1000,300,400,500,200"
  python -m formulakit irr                          # runs with the documented example inputs
  python -m formulakit                              # interactive, like the original calculator
  python -m formulakit docs --out FORMULAS.md       # regenerate the formula reference
  python -m formulakit export --out ../../docs/formulas/formulas.json
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from . import GROUPS, REGISTRY
from .registry import parse


def fmt(f, v) -> str:
    if v is None:
        return "no solution for these inputs"
    if f.out == "table":
        head = list(v[0])
        lines = ["  ".join(f"{h:>10}" for h in head)]
        lines += ["  ".join(f"{r[h]:>10.2f}" if isinstance(r[h], float) else f"{r[h]:>10}" for h in head) for r in v]
        return "\n".join(lines)
    if f.out == "gate":
        return f"{'PASS' if v['pass'] else 'FAIL'}  (change {v['change']:.2%})"
    if f.out == "list":
        return ", ".join(f"{x:g}" if isinstance(x, (int, float)) else str(x) for x in v)
    if f.out == "pct":
        return f"{v:.4%}"
    if f.out == "money":
        return f"{v:,.2f}"
    return f"{v:,.6g}"


def _list():
    for g, name in GROUPS.items():
        print(f"\n{name}")
        for f in REGISTRY.values():
            if f.group == g:
                print(f"  {f.key:22s} {f.title}")


def _interactive():
    key = input("Formula (or 'list'): ").strip().lower().replace(" ", "_")
    if key == "list":
        return _list()
    f = REGISTRY.get(key)
    if not f:
        print("Unknown formula. Try 'list'.")
        return
    print(f"{f.title}:  {f.formula}")
    raw = {}
    for p in f.params:
        v = input(f"{p.label} [{p.default}]: ").strip()
        raw[p.name] = v if v else p.default
    print(fmt(f, f.run(raw)))


def docs() -> str:
    out = ["# Formula reference",
           "",
           "*Generated by `python -m formulakit docs` from the code - every example below is computed, and the tests check them.*",
           ""]
    for g, name in GROUPS.items():
        out += [f"## {name}", ""]
        for f in (x for x in REGISTRY.values() if x.group == g):
            ex = f.examples[0]
            inputs = ", ".join(f"{p.label.lower()} = {ex[p.name]}" for p in f.params)
            val = fmt(f, f.run(ex))
            out += [f"### {f.title}", f"`{f.formula}`", "", f.explain, "",
                    f"*Example:* {inputs}", "", "```", f"python -m formulakit {f.key}", val, "```", ""]
    return "\n".join(out)


def export() -> dict:
    return {"groups": GROUPS,
            "formulas": [{"key": f.key, "group": f.group, "title": f.title, "formula": f.formula, "explain": f.explain,
                          "out": f.out, "params": [vars(p) for p in f.params],
                          "example_result": f.run(f.examples[0])} for f in REGISTRY.values()]}


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if not argv:
        return _interactive()
    cmd, rest = argv[0], argv[1:]
    if cmd == "list":
        return _list()
    if cmd in ("docs", "export"):
        out = Path(rest[rest.index("--out") + 1]) if "--out" in rest else None
        text = docs() if cmd == "docs" else json.dumps(export(), indent=1, ensure_ascii=False)
        if out:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text + "\n", encoding="utf-8")
            print(f"wrote {out}")
        else:
            print(text)
        return
    f = REGISTRY.get(cmd)
    if not f:
        sys.exit(f"Unknown formula '{cmd}'. Run: python -m formulakit list")
    raw = {}
    it = iter(rest)
    for a in it:
        if a.startswith("--"):
            raw[a[2:].replace("-", "_")] = next(it)
    unknown = set(raw) - {p.name for p in f.params}
    if unknown:
        sys.exit(f"Unknown input(s) {sorted(unknown)}; expected {[p.name for p in f.params]}")
    print(f"{f.title}:  {f.formula}")
    print(fmt(f, f.run(raw)))


if __name__ == "__main__":
    main()
