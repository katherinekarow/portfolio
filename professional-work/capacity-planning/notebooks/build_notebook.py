def run():
    ns: dict = {}
    nb_cells = []
    count = 0
    import os
    os.chdir(HERE)
    for kind, src in CELLS:
        if kind == "md":
            nb_cells.append({"cell_type": "markdown", "metadata": {}, "source": src.splitlines(True)})
            continue
        count += 1
        outputs = []
        figs = []
        orig_show = plt.show
        plt.show = lambda *a, **k: figs.append(plt.gcf())  # noqa: E731
        buf = io.StringIO()
        import ast
        tree = ast.parse(src)
        last = tree.body[-1] if tree.body and isinstance(tree.body[-1], ast.Expr) else None
        body = ast.Module(body=tree.body[:-1] if last else tree.body, type_ignores=[])
        with contextlib.redirect_stdout(buf):
            exec(compile(body, f"<cell {count}>", "exec"), ns)
            result = eval(compile(ast.Expression(last.value), f"<cell {count}>", "eval"), ns) if last else None
        plt.show = orig_show
        if buf.getvalue():
            outputs.append({"output_type": "stream", "name": "stdout", "text": buf.getvalue().splitlines(True)})
        for f in figs:
            png = io.BytesIO(); f.savefig(png, format="png", dpi=110); plt.close(f)
            outputs.append({"output_type": "display_data", "metadata": {},
                            "data": {"image/png": base64.b64encode(png.getvalue()).decode(), "text/plain": ["<Figure>"]}})
        if result is not None:
            data = {"text/plain": repr(result).splitlines(True)}
            if hasattr(result, "to_html"):
                data["text/html"] = result.to_html(max_rows=12).splitlines(True)
            outputs.append({"output_type": "execute_result", "execution_count": count, "metadata": {}, "data": data})
        nb_cells.append({"cell_type": "code", "execution_count": count, "metadata": {}, "outputs": outputs,
                         "source": src.splitlines(True)})
    nb = {"nbformat": 4, "nbformat_minor": 5, "cells": nb_cells,
          "metadata": {"kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"},
                       "language_info": {"name": "python"}}}
    for i, c in enumerate(nb["cells"]):
        c["id"] = f"cell-{i:02d}"
    (HERE / "walkthrough.ipynb").write_text(json.dumps(nb, indent=1))
    print("wrote walkthrough.ipynb with", count, "executed code cells")


if __name__ == "__main__":
    run()
