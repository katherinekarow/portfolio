"""python -m tunekit run [--rows 1000000] [--db bench.sqlite] [--repeat 3]

Builds the benchmark database (once), runs every case, prints a summary, and writes
RESULTS.md (plans before/after + timings) and figures/timings.png.
"""
from __future__ import annotations

import argparse
import platform
import textwrap
import sqlite3
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from . import bench, data
from .cases import CASES

ROOT = Path(__file__).resolve().parents[2]


def results_md(results: list[dict], n_rows: int) -> str:
    by = {c.name: c for c in CASES}
    out = ["# Benchmark results", "",
           f"_Generated by `python -m tunekit run` on {n_rows:,} appointments / ~{int(n_rows * 2.5):,} events · "
           f"SQLite {sqlite3.sqlite_version} · Python {platform.python_version()} · median of repeated runs._", "",
           "| Case | Before | After | Speed-up | Same result |", "|---|---:|---:|---:|---|"]
    for r in results:
        same = "yes" if r["same_result"] else f"**no - old query overstated by {r['overstatement_pct']:.0f}%**"
        out.append(f"| [{r['title']}](#{r['case']}) | {r['slow_s'] * 1000:,.0f} ms | {r['fast_s'] * 1000:,.1f} ms | "
                   f"{r['speedup']:,.1f}× | {same} |")
    for r in results:
        c = by[r["case"]]
        out += ["", f"## {r['title']}", f'<a id="{r["case"]}"></a>', "", c.lesson, "",
                "**Before**", "```sql", textwrap.dedent(c.slow_sql).strip(), "```",
                "Plan: " + " → ".join(f"`{p}`" for p in r["slow_plan"]), "",
                "**After**" + (f" (adds `{'`, `'.join(i.split(' ON ')[0].split()[-1] for i in c.fast_indexes)}`)" if c.fast_indexes else ""),
                "```sql", textwrap.dedent(c.fast_sql).strip(), "```",
                "Plan: " + " → ".join(f"`{p}`" for p in r["fast_plan"])]
        if c.fast_indexes:
            out += ["", "```sql"] + [i + ";" for i in c.fast_indexes] + ["```"]
        if r.get("alt"):
            a = r["alt"]
            out += ["", f"Also measured: {a['label']}: {a['seconds'] * 1000:,.0f} ms "
                        f"({'same result' if a['same_result'] else 'DIFFERENT result'}), "
                        f"{'slower' if a['seconds'] > r['fast_s'] else 'faster'} than the indexed version."]
    return "\n".join(out) + "\n"


def chart(results: list[dict], path: Path):
    fig, ax = plt.subplots(figsize=(8.5, 3.8))
    labels = [r["title"].split(" →")[0].split(":")[0] for r in results]
    y = range(len(results))
    ax.barh([i + 0.2 for i in y], [r["slow_s"] * 1000 for r in results], 0.4, color="#c9c8c2", label="before")
    ax.barh([i - 0.2 for i in y], [r["fast_s"] * 1000 for r in results], 0.4, color="#2a78d6", label="after")
    for i, r in enumerate(results):
        tag = f"{r['speedup']:.0f}× faster" if r["speedup"] >= 2 else f"{r['speedup']:.1f}×"
        if not r["same_result"]:
            tag += " · fixed a wrong total"
        ax.text(r["slow_s"] * 1000 * 1.15, i + 0.2, tag, va="center", fontsize=8.5, color="#0b0b0b")
    ax.set_xscale("log")
    ax.set_yticks(list(y)); ax.set_yticklabels(labels, fontsize=9); ax.invert_yaxis()
    ax.set_xlabel("Query time, ms (log scale)", color="#52514e")
    ax.set_xlim(right=max(r["slow_s"] for r in results) * 1000 * 12)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.legend(frameon=False, fontsize=8.5, loc="lower right")
    ax.set_title("Before vs after on 1M appointments", loc="left", fontsize=12, fontweight="bold")
    fig.tight_layout(); fig.savefig(path, dpi=150); plt.close(fig)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="tunekit")
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--rows", type=int, default=1_000_000)
    r.add_argument("--db", default="bench.sqlite")
    r.add_argument("--repeat", type=int, default=3)
    a = ap.parse_args(argv)
    db = Path(a.db)
    con = sqlite3.connect(db) if db.exists() else None
    if con is None or con.execute("SELECT COUNT(*) FROM sqlite_master WHERE name = 'appointments'").fetchone()[0] == 0 \
            or con.execute("SELECT COUNT(*) FROM appointments").fetchone()[0] != a.rows:
        print(f"building {db} with {a.rows:,} appointments ...")
        con = data.build(db, a.rows)
    results = bench.run_all(con, a.repeat)
    for r in results:
        flag = "" if r["same_result"] else f"   <- old query overstated the total by {r['overstatement_pct']:.0f}%"
        print(f"{r['case']:<26}{r['slow_s'] * 1000:>9,.1f} ms -> {r['fast_s'] * 1000:>8,.1f} ms  {r['speedup']:>7,.1f}x{flag}")
    (ROOT / "RESULTS.md").write_text(results_md(results, a.rows), encoding="utf-8")
    (ROOT / "figures").mkdir(exist_ok=True)
    chart(results, ROOT / "figures" / "timings.png")
    print("wrote RESULTS.md and figures/timings.png")


if __name__ == "__main__":
    main()
