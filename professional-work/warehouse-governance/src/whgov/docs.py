"""Generate documentation from the models: a catalog page with lineage, and a lineage chart."""
from __future__ import annotations

import re
import sqlite3
from pathlib import Path

import networkx as nx

from .project import LAYERS, Model

LAYER_COLOR = {"raw": "#8a8984", "stg": "#eda100", "core": "#2a78d6", "mart": "#1baf7a", "rpt": "#eb6834"}


def mermaid(g: nx.DiGraph) -> str:
    nid = lambda n: re.sub(r"\W", "_", n)
    out = ["flowchart LR"]
    for layer in LAYERS:
        nodes = sorted(n for n in g if n.startswith(layer + "."))
        if nodes:
            out.append(f"  subgraph {layer}")
            out += [f"    {nid(n)}[\"{n}\"]" for n in nodes]
            out.append("  end")
    out += [f"  {nid(a)} --> {nid(b)}" for a, b in sorted(g.edges)]
    return "\n".join(out)


def catalog_markdown(models: dict[str, Model], g: nx.DiGraph, con: sqlite3.Connection | None, test_results=None) -> str:
    lines = ["# Warehouse catalog", "",
             "_Generated by `python -m whgov docs` from the model files - do not edit by hand._", "",
             "```mermaid", mermaid(g), "```", ""]
    status = {}
    for r in test_results or []:
        status.setdefault(r["model"], []).append(r)
    lines += ["| Model | Grain | Rows | Tests | Owner |", "|---|---|---|---|---|"]
    for name in nx.lexicographical_topological_sort(g):
        if name not in models:
            continue
        m = models[name]
        rows = con.execute(f"SELECT COUNT(*) FROM {name}").fetchone()[0] if con else ""
        rs = status.get(name, [])
        t = f"{sum(r['passed'] for r in rs)}/{len(rs)} ✓" if rs else ""
        lines.append(f"| [`{name}`](#{name.replace('.', '')}) | {m.meta.get('grain', '')} | {rows:,} | {t} | {m.meta.get('owner', '')} |"
                     if con else f"| [`{name}`](#{name.replace('.', '')}) | {m.meta.get('grain', '')} | | {t} | {m.meta.get('owner', '')} |")
    lines.append("")
    for name in nx.lexicographical_topological_sort(g):
        if name not in models:
            continue
        m = models[name]
        lines += [f"## {name}", "", m.meta.get("description", ""), "",
                  f"**Grain:** {m.meta.get('grain', '')} · **Owner:** {m.meta.get('owner', '')} · "
                  f"**Reads:** {', '.join(f'`{p}`' for p in sorted(g.predecessors(name))) or '-'} · "
                  f"**Read by:** {', '.join(f'`{s}`' for s in sorted(g.successors(name))) or '-'}", "",
                  "| Column | Description |", "|---|---|"]
        lines += [f"| `{c}` | {d} |" for c, d in m.columns.items()]
        lines += ["", "Tests: " + " · ".join(f"`{t if len(t) < 70 else t[:67] + '...'}`" for t in m.tests), ""]
    return "\n".join(lines)


def lineage_png(g: nx.DiGraph, path: Path, highlight: str | None = None) -> Path:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    cols = {layer: sorted(n for n in g if n.startswith(layer + ".")) for layer in LAYERS}
    pos = {}
    for x, layer in enumerate(LAYERS):
        nodes = cols[layer]
        if x:   # barycentre ordering: place each node near the nodes it reads from (fewer crossings)
            nodes = sorted(nodes, key=lambda n: (-(sum(pos[p][1] for p in g.predecessors(n) if p in pos) /
                                                   max(1, sum(p in pos for p in g.predecessors(n)))), g.out_degree(n) == 0, n))
        for i, n in enumerate(nodes):
            pos[n] = (x, -(i - (len(nodes) - 1) / 2))
    up = nx.ancestors(g, highlight) | {highlight} if highlight else set(g)
    fig, ax = plt.subplots(figsize=(11, 4.2))
    for a, b in g.edges:
        on = a in up and b in up
        (x1, y1), (x2, y2) = pos[a], pos[b]
        ax.annotate("", xy=(x2 - 0.33, y2), xytext=(x1 + 0.33, y1),
                    arrowprops=dict(arrowstyle="-|>", color="#52514e" if on else "#e6e5e0", lw=1.4 if on else 1,
                                    connectionstyle=f"arc3,rad={0.5 if x2 - x1 > 1 else 0.08}", shrinkA=0, shrinkB=0))
    for n, (x, y) in pos.items():
        layer = n.split(".")[0]
        on = n in up
        ax.text(x, y, n.split(".")[1], ha="center", va="center", fontsize=9, color="white" if on else "#52514e",
                bbox=dict(boxstyle="round,pad=0.45", fc=LAYER_COLOR[layer] if on else "#fcfcfb", ec=LAYER_COLOR[layer], lw=1.5))
    for x, layer in enumerate(LAYERS):
        ax.text(x, max(p[1] for p in pos.values()) + 0.9, layer.upper(), ha="center", fontsize=10, fontweight="bold", color=LAYER_COLOR[layer])
    ax.set_xlim(-0.6, len(LAYERS) - 0.4)
    ax.set_ylim(min(p[1] for p in pos.values()) - 0.7, max(p[1] for p in pos.values()) + 1.3)
    ax.axis("off")
    if highlight:
        ax.set_title(f"Everything {highlight} depends on", loc="left", fontsize=12, fontweight="bold")
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return Path(path)
