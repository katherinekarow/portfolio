#!/usr/bin/env python3
"""
Rebuild the project tables on the front page (README.md) and the
project list used by the website (docs/projects.json).

How it finds projects:
  * every top-level folder is a SECTION (except docs, tools, and folders starting with . or _)
  * every sub-folder of a section that has a README.md is a PROJECT
  * from each project README it reads:
        # Title                      -> project name
        > One-line summary            -> description
        **Tools:** Python, Tableau    -> tools column
        **Live demo:** [label](url)   -> optional "Live demo" button on the website

Add a new section = make a new top-level folder with a README.md (first line "# Emoji Name").
Add a new project  = copy _template/ into a section and fill it in.
Runs automatically on every push (.github/workflows/update-index.yml), or by hand:
    python tools/build_index.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKIP = {"docs", "tools"}
# Sections listed here appear first, in this order; any new folder is added after them.
ORDER = ["professional-work", "analytics-methods", "recent-work", "data-analysis", "economics-finance", "python-fundamentals", "fun"]
START, END = "<!-- PROJECTS:START -->", "<!-- PROJECTS:END -->"
REPO_URL = "https://github.com/katherinekarow/portfolio/tree/main/"


def read_meta(readme: pathlib.Path):
    text = readme.read_text(encoding="utf-8")
    title = re.search(r"^#\s+(.+)$", text, re.M)
    summary = re.search(r"^>\s*(.+)$", text, re.M)
    tools = re.search(r"^\*\*Tools:\*\*\s*(.+)$", text, re.M)
    demo = re.search(r"^\*\*Live demo:\*\*\s*\[([^\]]+)\]\(([^)]+)\)", text, re.M)
    return {
        **({"demo": demo.group(2).strip(), "demo_label": demo.group(1).strip()} if demo else {}),
        "title": title.group(1).strip() if title else readme.parent.name,
        "summary": summary.group(1).strip() if summary else "",
        "tools": tools.group(1).strip() if tools else "",
    }


def sections():
    dirs = [d for d in ROOT.iterdir() if d.is_dir() and d.name not in SKIP and d.name[0] not in "._"]
    dirs.sort(key=lambda d: (ORDER.index(d.name) if d.name in ORDER else len(ORDER), d.name))
    for d in dirs:
        projects = []
        for p in sorted(x for x in d.iterdir() if x.is_dir() and (x / "README.md").exists()):
            meta = read_meta(p / "README.md")
            meta["path"] = f"{d.name}/{p.name}"
            projects.append(meta)
        if not projects:
            continue
        head = read_meta(d / "README.md") if (d / "README.md").exists() else {"title": d.name, "summary": ""}
        yield {"key": d.name, "title": head["title"], "summary": head["summary"], "projects": projects}


def main():
    data = list(sections())
    md = []
    for s in data:
        md.append(f"### <img src=\"docs/assets/sakura.svg\" alt=\"\" width=\"18\"> [{s['title']}]({s['key']}/)\n")
        if s["summary"]:
            md.append(f"{s['summary']}\n")
        md.append("| Project | What it is | Tools |\n|---|---|---|")
        for p in s["projects"]:
            live = f" · [live demo]({p['demo']})" if p.get("demo") else ""
            md.append(f"| [{p['title']}]({p['path']}/){live} | {p['summary']} | {p['tools']} |")
        md.append("")
    block = f"{START}\n<!-- This part is generated by tools/build_index.py — edit project READMEs instead. -->\n\n" + "\n".join(md) + f"\n{END}"

    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    readme.write_text(text, encoding="utf-8")

    for s in data:
        for p in s["projects"]:
            p["url"] = REPO_URL + p["path"]
    (ROOT / "docs" / "projects.json").write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{sum(len(s['projects']) for s in data)} projects in {len(data)} sections")


if __name__ == "__main__":
    main()
